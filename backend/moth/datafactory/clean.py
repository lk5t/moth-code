"""Cleaning, quality scoring, deduplication and decontamination.

* ``normalize`` — Unicode NFC, no control characters, no trailing spaces, at most two blank lines.
* ``scrub`` — e-mail addresses, phone numbers and credentials are replaced with placeholders.
* ``quality`` — a 0..1 score from measurable signals (length, letter ratio, repetition, common-word
  ratio, sentence endings; for code: it parses, sane line lengths, not generated/minified).
* ``Deduper`` — exact duplicates (normalised text hash) and near duplicates (MinHash over word
  5-grams with LSH banding, estimated Jaccard ≥ 0.8) are removed across *all* sources of a build.
* ``Decontaminator`` — any training record sharing a 13-word sequence with an evaluation item is
  dropped, so benchmarks measure what the model learned rather than what it memorised.
"""

from __future__ import annotations

import ast
import hashlib
import re
import unicodedata
from collections import Counter
from typing import Any, Iterable

import numpy as np

CONTROL = re.compile(r"[\x00-\x08\x0b\x0c\x0e-\x1f\x7f]")
BLANKS = re.compile(r"\n{3,}")
TRAILING = re.compile(r"[ \t]+\n")
EMAIL = re.compile(r"\b[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}\b")
PHONE = re.compile(r"(?<!\w)(?:\+?\d{1,3}[ .-]?)?\(?\d{3}\)?[ .-]\d{3}[ .-]\d{4}(?!\w)")
SECRET = re.compile(r"\b(?:sk|pk|rk|ghp|gho|xox[abp])[-_][A-Za-z0-9_-]{16,}\b|\bAKIA[0-9A-Z]{16}\b")
WORD = re.compile(r"[a-z0-9']+")
COMMON = frozenset(
    "the of and to a in is it that for on was with as he she they i you we be at by this are have from or "
    "an not but his her their there were what which one all can had has will would if when so do no my "
    "your our more about up out who them then than into its also some time like just how".split())


def normalize(text: str) -> str:
    text = unicodedata.normalize("NFC", text).replace("\r\n", "\n").replace("\r", "\n")
    text = CONTROL.sub("", text)
    text = TRAILING.sub("\n", text)
    return BLANKS.sub("\n\n", text).strip()


def scrub(text: str) -> tuple[str, int]:
    n = 0
    for rx, repl in ((SECRET, "[secret]"), (EMAIL, "[email]"), (PHONE, "[phone]")):
        text, k = rx.subn(repl, text)
        n += k
    return text, n


def record_text(rec: dict[str, Any]) -> str:
    if "messages" in rec:
        return "\n".join(m["content"] for m in rec["messages"])
    return rec["text"]


def words(text: str) -> list[str]:
    return WORD.findall(text.lower())


def _prose_quality(text: str) -> tuple[float, str | None]:
    w = words(text)
    if len(w) < 3:
        return 0.0, "too_short"
    letters = sum(c.isalpha() for c in text)
    alpha = letters / max(1, len(text))
    if alpha < 0.45:
        return 0.1, "not_prose"
    common = sum(x in COMMON for x in w) / len(w)
    uniq = len(set(w)) / len(w)
    lines = [l for l in text.split("\n") if l.strip()]
    dup_lines = 1 - len(set(lines)) / max(1, len(lines))
    tri = Counter(zip(w, w[1:], w[2:]))
    top_tri = (max(tri.values()) * 3 / len(w)) if tri and len(w) > 30 else 0.0
    mean_len = sum(map(len, w)) / len(w)
    ends = sum(l.rstrip()[-1:] in ".!?:\"')" for l in lines) / max(1, len(lines))
    if top_tri > 0.3 or dup_lines > 0.5:
        return 0.15, "repetitive"
    score = (0.25 * min(1.0, common / 0.3) + 0.2 * min(1.0, alpha / 0.7) + 0.15 * min(1.0, uniq / 0.4)
             + 0.15 * (1.0 if 3.0 <= mean_len <= 7.5 else 0.3) + 0.15 * ends + 0.1 * (1 - dup_lines))
    return round(score, 4), None


def _code_quality(text: str) -> tuple[float, str | None]:
    lines = text.split("\n")
    if len(lines) < 3:
        return 0.0, "too_short"
    longest = max(map(len, lines))
    if longest > 400:
        return 0.1, "minified"
    head = text[:600].lower()
    if "auto-generated" in head or "autogenerated" in head or "do not edit" in head:
        return 0.1, "generated"
    parses = 1.0
    try:
        ast.parse(text)
    except (SyntaxError, ValueError, RecursionError, MemoryError):
        parses = 0.4
    comments = sum(l.strip().startswith("#") for l in lines) / len(lines)
    blank = sum(not l.strip() for l in lines) / len(lines)
    score = 0.5 * parses + 0.2 * (1.0 if longest <= 120 else 0.6) + 0.15 * min(1.0, comments / 0.05 + 0.3) \
        + 0.15 * (1.0 if blank < 0.4 else 0.4)
    return round(min(1.0, score), 4), None


def quality(rec: dict[str, Any]) -> tuple[float, str | None]:
    if "messages" in rec:
        msgs = rec["messages"]
        if len(msgs) < 2 or msgs[-1]["role"] != "assistant":
            return 0.0, "incomplete_conversation"
        if any(not m["content"].strip() for m in msgs):
            return 0.0, "empty_turn"
        answer = msgs[-1]["content"]
        if rec["domain"] == "code" or "```" in answer:
            return 0.85, None  # curated benchmark-style pairs: kept
        if rec["domain"] in ("math", "reasoning"):
            return 0.85, None
        if not words(answer):
            return 0.0, "too_short"
        if len(words(answer)) < 20:  # short factual answers ("Paris.") are legitimate
            return 0.6, None
        score, why = _prose_quality(answer)
        return max(score, 0.5) if why is None else score, why
    if rec["domain"] == "code":
        return _code_quality(rec["text"])
    return _prose_quality(rec["text"])


def h64(s: str) -> int:
    """Deterministic 64-bit hash (Python's ``hash`` changes between processes, builds must not)."""
    return int.from_bytes(hashlib.blake2b(s.encode(), digest_size=8).digest(), "little")


def exact_key(text: str) -> bytes:
    return hashlib.blake2b(" ".join(words(text)).encode(), digest_size=12).digest()


_P = (1 << 61) - 1
_RNG = np.random.default_rng(20251106)
N_PERM, BANDS = 32, 8  # 8 bands × 4 rows → near-certain detection at Jaccard ≥ 0.8
_A = _RNG.integers(1, _P - 1, size=N_PERM, dtype=np.uint64)
_B = _RNG.integers(0, _P - 1, size=N_PERM, dtype=np.uint64)


def minhash(text: str, max_words: int = 1500) -> np.ndarray | None:
    w = words(text)[:max_words]
    if len(w) < 8:
        return None
    sh = np.fromiter((h64(" ".join(w[i:i + 5])) & 0x1FFFFFFFFFFFFFFF for i in range(len(w) - 4)), dtype=np.uint64)
    sh = np.unique(sh)
    # universal hashing with 64-bit wrap-around: enough mixing for deduplication
    vals = (sh[None, :] * _A[:, None] + _B[:, None]) & np.uint64(_P)
    return vals.min(axis=1)


class Deduper:
    def __init__(self) -> None:
        self.exact: set[bytes] = set()
        self.bands: list[dict[bytes, int]] = [dict() for _ in range(BANDS)]
        self.sigs: list[np.ndarray] = []

    def check(self, text: str, near: bool = True) -> str | None:
        """Return ``"exact"``/``"near"`` for a duplicate, else register the text and return ``None``."""
        k = exact_key(text)
        if k in self.exact:
            return "exact"
        sig = minhash(text) if near else None
        if sig is not None:
            rows = N_PERM // BANDS
            keys = [sig[b * rows:(b + 1) * rows].tobytes() for b in range(BANDS)]
            for b, key in enumerate(keys):
                other = self.bands[b].get(key)
                if other is not None and float(np.mean(self.sigs[other] == sig)) >= 0.8:
                    return "near"
            idx = len(self.sigs)
            self.sigs.append(sig)
            for b, key in enumerate(keys):
                self.bands[b].setdefault(key, idx)
        self.exact.add(k)
        return None


class Decontaminator:
    N = 13

    def __init__(self, eval_texts: Iterable[str]) -> None:
        self.grams: set[int] = set()
        for t in eval_texts:
            w = words(t)
            if len(w) < self.N:
                self.grams.add(h64(" ".join(w)))  # short items: the whole item must not appear verbatim
                continue
            for i in range(len(w) - self.N + 1):
                self.grams.add(h64(" ".join(w[i:i + self.N])))

    def contaminated(self, text: str) -> bool:
        w = words(text)
        if len(w) < self.N:
            return h64(" ".join(w)) in self.grams
        for i in range(len(w) - self.N + 1):
            if h64(" ".join(w[i:i + self.N])) in self.grams:
                return True
        return False
