import { act, cleanup, fireEvent, render, screen, waitFor } from "@testing-library/react";
import { afterEach, beforeEach, expect, it, vi } from "vitest";
const mocks=vi.hoisted(()=>({get:vi.fn(),post:vi.fn()}));
vi.mock("@/lib/backend",()=>({get:mocks.get,post:mocks.post}));
vi.mock("@/lib/cloud",()=>({useCloudStatus:()=>({status:{signed_in:true,available:true,model:{name:"MOTH"}},reload:vi.fn()})}));
vi.mock("@/lib/cloud-progress",()=>({useCloudProgress:()=>({data:{current:{name:"MOTH"},serving:{accepting_requests:true}}})}));
vi.mock("@/lib/hooks",()=>({useResource:(path:string)=>({data:path.startsWith('/api/conversations') ? [{id:1,title:"Conversation"}] : null,reload:vi.fn()})}));
vi.mock("@/features/agent/AgentPanel",()=>({AgentPanel:()=>null}));
vi.mock("@/features/account/AccountDialog",()=>({openAccountDialog:vi.fn()}));
import { ChatPanel } from "@/features/chat/ChatPanel";
import { appStore } from "@/lib/app-state";
import { _testing } from "@/lib/events";
beforeEach(()=>{appStore.setState({chatRequest:null,chatSession:{conversationId:null,title:"New conversation",busy:false}});vi.stubGlobal("ResizeObserver",class {observe(){} disconnect(){} unobserve(){}});HTMLElement.prototype.scrollTo=vi.fn();});
afterEach(()=>{cleanup();vi.unstubAllGlobals();});
it("does not pull a reader to the bottom while new tokens arrive",async()=>{
  mocks.get.mockResolvedValue([{id:1,role:"user",content:"Question"},{id:2,role:"assistant",content:"Old answer"}]);
  render(<ChatPanel general/>);
  act(()=>appStore.setState({chatRequest:{sequence:1,conversationId:1}}));
  await screen.findByText("Old answer");
  const scroll=screen.getByText("Old answer").closest('.overflow-y-auto') as HTMLElement;
  const move=vi.fn();scroll.scrollTo=move;
  Object.defineProperty(scroll,"scrollHeight",{configurable:true,value:1000});Object.defineProperty(scroll,"clientHeight",{configurable:true,value:200});
  act(()=>_testing.dispatch({topic:"chat",ts:1,conversation_id:1,message_key:"new",kind:"start"}));
  move.mockClear();scroll.scrollTop=100;fireEvent.scroll(scroll);
  act(()=>_testing.dispatch({topic:"chat",ts:2,conversation_id:1,message_key:"new",kind:"token",text:"New text"}));
  expect(move).not.toHaveBeenCalled();expect(scroll.scrollTop).toBe(100);
  act(()=>_testing.dispatch({topic:"chat",ts:3,conversation_id:1,message_key:"new",kind:"done",text:"New text",message_id:3}));
  expect(screen.getByText("Previous answer · retained in history")).toBeInTheDocument();
  mocks.post.mockResolvedValue({conversation_id:1});
  fireEvent.click(screen.getByRole("button",{name:"Regenerate"}));
  await waitFor(()=>expect(mocks.post).toHaveBeenCalledWith('/api/chat',expect.objectContaining({regenerate:true,message:"Question",conversation_id:1})));
  expect(screen.getAllByText("Question")).toHaveLength(1);
});

